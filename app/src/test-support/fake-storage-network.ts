import { createServer, IncomingMessage, Server, ServerResponse } from 'node:http';
import { AddressInfo, connect, Socket } from 'node:net';

export interface FakeStorageError {
  readonly status: number;
  /** `null` answers with an empty body, like a gateway that is not S3. */
  readonly code: string | null;
}

export interface FakeS3Server {
  readonly host: string;
  readonly port: number;
  /** Methods and paths received, for asserting what the client really sent. */
  readonly requests: readonly string[];
  stop(): Promise<void>;
}

export interface FakeEgressProxy {
  readonly url: string;
  /** `host:port` of every CONNECT tunnel the client asked for. */
  readonly connectTargets: readonly string[];
  stop(): Promise<void>;
}

const LOOPBACK_HOST = '127.0.0.1';
/**
 * Squid 6.13 (the image the deploy pins) refusing a CONNECT tunnel, captured
 * from the real proxy with the stylesheet dropped. Its unclosed `<hr>`/`<br>`
 * break the SDK's XML parser, so the SDK throws a plain `Error` with no S3
 * `Code`; an empty body would instead yield `Unknown` and hide that case.
 */
const SQUID_ACCESS_DENIED_PAGE = [
  '<!DOCTYPE html PUBLIC "-//W3C//DTD HTML 4.01//EN" "http://www.w3.org/TR/html4/strict.dtd">',
  '<html><head>',
  '<meta http-equiv="Content-Type" content="text/html; charset=utf-8">',
  '<title>ERROR: The requested URL could not be retrieved</title>',
  '</head><body id=ERR_ACCESS_DENIED>',
  '<div id="titles">',
  '<h1>ERROR</h1>',
  '<h2>The requested URL could not be retrieved</h2>',
  '</div>',
  '<hr>',
  '<div id="content">',
  '<blockquote id="error">',
  '<p><b>Access Denied.</b></p>',
  '</blockquote>',
  '<p>Access control configuration prevents your request from being allowed at this time.</p>',
  '<br>',
  '</div>',
  '<hr>',
  '<div id="footer">',
  '<p>Generated by fake-squid (squid/6.13)</p>',
  '<!-- ERR_ACCESS_DENIED -->',
  '</div>',
  '</body></html>',
  '',
].join('\n');

/** S3-compatible endpoint that answers every request with one S3 error document (or none). */
export async function startFakeS3Server(error: FakeStorageError): Promise<FakeS3Server> {
  const requests: string[] = [];
  const server = createServer((request: IncomingMessage, response: ServerResponse) => {
    requests.push(`${request.method ?? ''} ${request.url ?? ''}`);
    request.resume();
    const body = error.code === null
      ? ''
      : `<?xml version="1.0" encoding="UTF-8"?><Error><Code>${error.code}</Code><Message>fake</Message></Error>`;
    response.writeHead(error.status, {
      'Content-Length': Buffer.byteLength(body),
      'Content-Type': 'application/xml',
    });
    response.end(body);
  });
  const port = await listen(server);
  return { host: LOOPBACK_HOST, port, requests, stop: () => close(server, new Set()) };
}

/**
 * Minimal CONNECT proxy like the Squid egress proxy. It records the exact
 * host the client tunnels to, then either forwards or refuses the tunnel with
 * the same 403 page as Squid.
 */
export async function startFakeEgressProxy(options: { readonly forward: boolean }): Promise<FakeEgressProxy> {
  const connectTargets: string[] = [];
  const sockets = new Set<Socket>();
  const server = createServer((_request, response) => {
    // Plain HTTP forwarding would bypass the CONNECT allowlist.
    response.writeHead(405);
    response.end();
  });
  server.on('connection', (socket: Socket) => {
    sockets.add(socket);
    socket.on('close', () => sockets.delete(socket));
  });
  server.on('connect', (request: IncomingMessage, clientSocket: Socket, head: Buffer) => {
    const target = request.url ?? '';
    connectTargets.push(target);
    if (!options.forward) {
      clientSocket.end([
        'HTTP/1.1 403 Forbidden',
        'Server: squid/6.13',
        'Content-Type: text/html;charset=utf-8',
        `Content-Length: ${Buffer.byteLength(SQUID_ACCESS_DENIED_PAGE)}`,
        'X-Squid-Error: ERR_ACCESS_DENIED 0',
        '',
        SQUID_ACCESS_DENIED_PAGE,
      ].join('\r\n'));
      return;
    }
    const separator = target.lastIndexOf(':');
    const upstream = connect(Number(target.slice(separator + 1)), target.slice(0, separator), () => {
      clientSocket.write('HTTP/1.1 200 Connection Established\r\n\r\n');
      if (head.length > 0) upstream.write(head);
      upstream.pipe(clientSocket);
      clientSocket.pipe(upstream);
    });
    sockets.add(upstream);
    upstream.on('close', () => sockets.delete(upstream));
    upstream.on('error', () => clientSocket.destroy());
    clientSocket.on('error', () => upstream.destroy());
  });
  const port = await listen(server);
  return {
    connectTargets,
    stop: () => close(server, sockets),
    url: `http://${LOOPBACK_HOST}:${port}`,
  };
}

async function listen(server: Server): Promise<number> {
  await new Promise<void>((resolve, reject) => {
    server.once('error', reject);
    server.listen(0, LOOPBACK_HOST, () => resolve());
  });
  return (server.address() as AddressInfo).port;
}

async function close(server: Server, sockets: Set<Socket>): Promise<void> {
  for (const socket of sockets) socket.destroy();
  server.closeAllConnections();
  await new Promise<void>((resolve) => server.close(() => resolve()));
}
